#!/usr/bin/env bash
# Shared by install/uninstall. New units can retain legacy data paths in place.
GATEWAY=jibas-wg-gateway.service
BRIDGE=jibas-wg-bridge.service
LEGACY_GATEWAY=wagw-gateway.service
LEGACY_BRIDGE=wagw-bridge.service
UNIT_DIR=/etc/systemd/system
NGINX_CONF=/etc/nginx/conf.d/jibas-wg.conf
LEGACY_NGINX_CONF=/etc/nginx/conf.d/wagw.conf
NGINX_MARKER='# JIBAS WG MANAGED DASHBOARD - generated by install.sh'
LEGACY_NGINX_MARKER='# WAGW MANAGED DASHBOARD - generated by install.sh'

select_layout() {
 TARGET=/opt/jibas-wg STATE=/etc/jibas-wg RUNTIME=/opt/jibas-wg-runtime CACHE=/var/cache/jibas-wg-npm
 SERVICE_USER=jibas-wg LEGACY_LAYOUT=0
 for item in /opt/wagw /etc/wagw /opt/wagw-runtime "$TARGET" "$STATE" "$RUNTIME"; do
  [[ ! -L $item ]] || die "Path instalasi tidak boleh berupa symlink: $item"
 done
 if [[ -f /opt/wagw/config.json || -e /opt/wagw/sessions || -e /opt/wagw/dashboard-auth.json || -e /etc/wagw/dashboard.htpasswd ||
       -e $UNIT_DIR/$LEGACY_GATEWAY || -e $UNIT_DIR/$LEGACY_BRIDGE || -e $LEGACY_NGINX_CONF ]]; then
  [[ ! -e $TARGET/config.json && ! -e $TARGET/sessions && ! -e $TARGET/dashboard-auth.json ]] ||
   die 'Data JIBAS WG dan data instalasi lama sama-sama ada. Tinjau sebelum migrasi.'
  TARGET=/opt/wagw STATE=/etc/wagw RUNTIME=/opt/wagw-runtime CACHE=/var/cache/wagw-npm
  SERVICE_USER=wagw LEGACY_LAYOUT=1
 fi
 NODE="$RUNTIME/node/bin/node"
}

assert_unit_owned() {
 local unit=$1 entry=$2 alternate=${3:-} file="$UNIT_DIR/$1" fragment dropins exec
 fragment=$(systemctl show -p FragmentPath --value "$unit" 2>/dev/null || true)
 [[ -z $fragment || $fragment == "$file" ]] || die "Service $unit belongs to another installation: $fragment"
 if [[ -e $file || -L $file ]]; then
  dropins=$(systemctl show -p DropInPaths --value "$unit" 2>/dev/null || true)
  [[ ! -L $file && -z $dropins ]] || die "Refusing to alter unmanaged $file (symlink or drop-in)"
  exec=$(grep '^ExecStart=' "$file" || true)
  if [[ $exec != "ExecStart=$NODE $TARGET/deployment/$entry" && (-z $alternate || $exec != "ExecStart=$NODE $TARGET/deployment/$alternate") ]]; then
   die "Refusing to alter unmanaged $file"
  fi
 elif [[ -n $fragment ]]; then
  die "Service $unit references a missing unit file: $fragment"
 fi
}

assert_owned_nginx() {
 local file=$1 marker=$2
 if [[ -e $file || -L $file ]]; then
  [[ ! -L $file ]] && grep -Fxq "$marker" "$file" || die "Refusing to alter unmanaged $file"
 fi
}

assert_owned_installation() {
 assert_unit_owned "$GATEWAY" start-gateway.js
 assert_unit_owned "$BRIDGE" bridge.js
 assert_unit_owned "$LEGACY_GATEWAY" start-wagw.js
 assert_unit_owned "$LEGACY_BRIDGE" bridge.js
 assert_owned_nginx "$NGINX_CONF" "$NGINX_MARKER"
 assert_owned_nginx "$LEGACY_NGINX_CONF" "$LEGACY_NGINX_MARKER"
}

gateway_pids() {
 local unit
 for unit in "$GATEWAY" "$LEGACY_GATEWAY"; do
  if [[ -f $UNIT_DIR/$unit ]]; then systemctl show -p MainPID --value "$unit" 2>/dev/null || true; fi
 done
}

listeners_belong_to() {
 local listeners=$1 owners=$2 found='' pid parent line
 [[ -n $owners && -n $listeners ]] || return 1
 while IFS= read -r line; do
  [[ $line =~ pid=[1-9][0-9]* ]] || return 1
 done <<< "$listeners"
 while read -r pid; do
  found=1
  if grep -Fxq "$pid" <<< "$owners"; then continue; fi
  parent=$(awk '$1=="PPid:" {print $2}' "/proc/$pid/status" 2>/dev/null) || return 1
  [[ $parent =~ ^[1-9][0-9]*$ ]] && grep -Fxq "$parent" <<< "$owners" || return 1
 done < <(grep -oE 'pid=[1-9][0-9]*' <<< "$listeners" | cut -d= -f2 | sort -u)
 [[ -n $found ]]
}

# Nginx sockets can be shared. Check configured vhosts as well as owning PIDs.
nginx_owns_dashboard() {
 local port=$1 listeners=$2 master rendered
 [[ -f $NGINX_CONF || -f $LEGACY_NGINX_CONF ]] || return 1
 master=$(systemctl show -p MainPID --value nginx.service 2>/dev/null || true)
 listeners_belong_to "$listeners" "$master" || return 1
 rendered=$(nginx -T 2>&1) || return 1
 awk -v port="$port" -v file="$NGINX_CONF" -v legacy="$LEGACY_NGINX_CONF" '
 /^# configuration file / { section=$4; sub(/:$/, "", section); waiting=0 }
 {
   line=$0; sub(/#.*/, "", line)
   if (waiting && line !~ /^[[:space:]]*$/) { line="listen " line; waiting=0 }
   while (match(line,/(^|[ \t;{}])listen[ \t]+[^ \t;{}]+/)) {
     bind=substr(line,RSTART,RLENGTH); line=substr(line,RSTART+RLENGTH)
     sub(/.*listen[ \t]+/, "", bind); sub(/^.*:/, "", bind)
     if (bind == port) { if (section == file || section == legacy) owned=1; else other=1 }
   }
   if (line ~ /(^|[ \t;{}])listen[ \t]*$/) waiting=1
 }
 END { exit !(owned && !other) }' <<< "$rendered"
}

probe_public_port() {
 local port=$1 listeners
 listeners=$(ss -H -ltnp "sport = :$port") || die "Cannot inspect TCP port $port"
 if [[ -z $listeners ]]; then
  printf 'Port dashboard %s tersedia.\n' "$port"
 elif nginx_owns_dashboard "$port" "$listeners" || listeners_belong_to "$listeners" "$(gateway_pids)"; then
  printf 'Port dashboard %s milik JIBAS WG. Instalasi akan memperbaiki instance ini.\n' "$port"
 else
  printf '%s\n' "$listeners" >&2
  die "Port dashboard $port dipakai aplikasi lain. Ubah port pada config.json atau gunakan --port PORT; jangan ubah db_port."
 fi
}
