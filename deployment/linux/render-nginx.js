'use strict';
function renderNginx(port,backendPort){
 for(const value of [port,backendPort])if(!Number.isInteger(Number(value))||Number(value)<1||Number(value)>65535)throw Error('Invalid port');
 if(Number(port)===Number(backendPort))throw Error('Public/backend ports must differ');
 return `# WAGW MANAGED DASHBOARD - generated by install.sh
server {
    listen ${Number(port)} ssl;
    server_name _;
    ssl_certificate /etc/wagw/dashboard.crt;
    ssl_certificate_key /etc/wagw/dashboard.key;
    ssl_protocols TLSv1.2 TLSv1.3;
    error_page 497 =301 https://$host:$server_port$request_uri;
    auth_basic "WAGW Dashboard";
    auth_basic_user_file /etc/wagw/dashboard.htpasswd;
    set $wagw_bad_origin 0;
    if ($http_origin != "") { set $wagw_bad_origin 1; }
    if ($http_origin = "$scheme://$http_host") { set $wagw_bad_origin 0; }
    if ($wagw_bad_origin = 1) { return 403; }
    client_max_body_size 50m;
    location = /api/apply-update { return 403; }
    location = /api/update-baileys { return 403; }
    location / {
        proxy_pass http://127.0.0.1:${Number(backendPort)};
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header Authorization "";
        proxy_read_timeout 120s;
    }
}
`;
}
module.exports={renderNginx};
if(require.main===module){try{process.stdout.write(renderNginx(process.argv[2],process.argv[3]));}catch(e){console.error(e.message);process.exitCode=1;}}
