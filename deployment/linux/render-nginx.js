'use strict';
function renderNginx(port,backendPort,{legacyState=false,ipv6=false}={}){
 for(const value of [port,backendPort])if(!Number.isInteger(Number(value))||Number(value)<1||Number(value)>65535)throw Error('Invalid port');
 if(Number(port)===Number(backendPort))throw Error('Public/backend ports must differ');
  const state=legacyState?'/etc/wagw':'/etc/jibas-wg';
  return `# JIBAS WG MANAGED DASHBOARD - generated by install.sh
server {
    listen ${Number(port)} ssl;${ipv6?`\n    listen [::]:${Number(port)} ssl;`:''}
    server_name _;
    ssl_certificate ${state}/dashboard.crt;
    ssl_certificate_key ${state}/dashboard.key;
    ssl_protocols TLSv1.2 TLSv1.3;
    error_page 497 =301 https://$host:$server_port$request_uri;
    auth_basic off;
    set $jibas_wg_bad_origin 0;
    if ($http_origin != "") { set $jibas_wg_bad_origin 1; }
    if ($http_origin = "$scheme://$http_host") { set $jibas_wg_bad_origin 0; }
    if ($jibas_wg_bad_origin = 1) { return 403; }
    client_max_body_size 50m;
    location = /healthz { return 404; }
    location = /api/apply-update { return 403; }
    location = /api/update-baileys { return 403; }
    location / {
        proxy_pass http://127.0.0.1:${Number(backendPort)};
        proxy_http_version 1.1;
        proxy_set_header Host $http_host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header Authorization "";
        proxy_read_timeout 120s;
    }
}
`;
}
module.exports={renderNginx};
if(require.main===module){
 try {
  const [port,backend,...flags]=process.argv.slice(2);
  if(flags.some(flag=>!['--legacy-state','--ipv6'].includes(flag)))throw Error('Unknown Nginx option');
  process.stdout.write(renderNginx(port,backend,{legacyState:flags.includes('--legacy-state'),ipv6:flags.includes('--ipv6')}));
 } catch(e){console.error(e.message);process.exitCode=1;}
}
